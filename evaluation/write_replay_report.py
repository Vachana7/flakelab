"""Write docs/REPLAY.md from evaluation/results/replay.json (never by hand)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).parent.parent


def yes(flag: bool) -> str:
    return "blocked" if flag else "not blocked"


def main() -> None:
    rows = json.loads((ROOT / "evaluation/results/replay.json").read_text())
    version = rows[0]["pipedelta_version"]
    now = sum(r["blocked_at_default"] for r in rows)
    old = sum(r.get("v0_4_level") == "high" for r in rows)
    ziz = sum(bool(r.get("zizmor_high")) for r in rows)
    lines = [
        "# Incident replay benchmark",
        "",
        "Generated by `evaluation/write_replay_report.py` from `evaluation/results/replay.json`.",
        "",
        (
            f"Nine real CI/CD attacks from December 2024 to November 2026, rebuilt as the workflow "
            f"change each one made or depended on. PipeDelta {version} blocks **{now} of {len(rows)}** "
            f"at the default level (high). Version 0.4 blocked {old}. zizmor 1.32 raised a new "
            f"high-severity finding on {ziz}."
        ),
        "",
        (
            "| Incident | Date | How it arrived | Change replayed | v0.4 | "
            f"v{version} | zizmor 1.32 (new high) |"
        ),
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| [{r['incident']}]({r['source']}) | {r['date']} | {r['delivery']} | {r['title']} | "
            f"{r.get('v0_4_level', '')} | {r['level']} | "
            f"{'yes' if r.get('zizmor_high') else 'no'} |"
        )
    lines += [
        "",
        "## Read this before quoting the numbers",
        "",
        (
            "- The cases are reconstructions from public write-ups, not the attackers' exact files. "
            "Each `case.json` links its source and says what was simplified."
        ),
        (
            "- They were written on 18 Nov 2026, the same day as the v0.5 rules, by the same team. "
            "The rules were designed from the incident reports, and one rule (every secret at once, "
            "`toJSON(secrets)`, raised to high) was added after case r04 was first missed. They are "
            "more grounded than the self-written cases in `evaluation/attacks`, but still not an "
            "independent test."
        ),
        (
            "- zizmor judges whole files, not changes, and is not built for several of these shapes "
            "(direct pushes, memory dumps, OIDC on outsider triggers). Its column shows what kind of "
            "change each tool notices, not which tool is better. Use both."
        ),
        (
            "- r01 (tj-actions) arrived as an upstream tag move. It is replayed as a diff of the "
            "action's own `action.yml`, which is what upstream review (on the roadmap) would see. "
            "Today PipeDelta only sees it if the action lives in your repository."
        ),
        (
            "- In r05 and r06, v0.4 already blocked the change, but only because a write permission "
            "was added. v0.5 names the actual risk (self-approval by label; OIDC identity in a "
            "workflow outsiders can start)."
        ),
        (
            "- r02 and r03 were direct pushes with stolen credentials. A pull-request check never runs "
            "for them; PipeDelta catches them only when it also runs on `push` (new in v0.5)."
        ),
        "",
        "Reproduce: `python evaluation/run_replay.py evaluation/results/replay.json --zizmor`.",
    ]
    (ROOT / "docs/REPLAY.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
